export type EventDate = `${number}-${number}-${number}`;
export type EventStatus = "scheduled" | "cancelled" | "postponed";

export type Event = {
    id: string;
    // First artist is used as the calendar label/headliner.
    artists: string[];
    tourName: string;
    // Use YYYY-MM-DD.
    date: EventDate;
    prefecture: string;
    venue: string;
    genres: string[];
    // True when the main purpose is a visiting international artist's Japan show.
    isInternational: boolean;
    // Use null when ticket information is not published yet.
    ticketUrl: string | null;
    // Artist, venue, or organizer event page used to verify event details.
    officialUrl: string | null;
    status: EventStatus;
    // Operational dates. Existing older events may not have these yet.
    candidateCreatedAt?: string;
    publishedAt?: string;
    updatedAt?: string;
};

